import type { INestApplication } from '@nestjs/common';
import { SwaggerModule, type OpenAPIObject } from '@nestjs/swagger';
import { DISABLED_AUTH_PATHS, loadActor, type Auth } from '@starter/auth';
import type { Env, FeatureFlags } from '@starter/config';
import type { DbHandle } from '@starter/db';
import { fromNodeHeaders } from 'better-auth/node';
import type { NextFunction, Request, Response } from 'express';
import { buildOpenApiDocument } from '../../common/openapi.js';
import { STARTER_VERSION } from '../health/health.service.js';

type Json = Record<string, unknown>;

/**
 * Better Auth routes are mounted as Express middleware (not Nest controllers), so Swagger cannot
 * discover them. We import the specification generated by Better Auth's openAPI plugin, prefix
 * paths with the mount point and namespace its component schemas.
 */
export async function betterAuthPaths(auth: Auth, basePath = '/api/auth'): Promise<{ paths: OpenAPIObject['paths']; schemas: Record<string, Json> }> {
  const spec = (await (auth.api as unknown as { generateOpenAPISchema: () => Promise<Json> }).generateOpenAPISchema()) as {
    paths: Record<string, Record<string, Json>>;
    components?: { schemas?: Record<string, Json> };
  };
  const rename = (s: string) => s.replace(/#\/components\/schemas\/([A-Za-z0-9_]+)/g, '#/components/schemas/Auth$1');
  const paths: OpenAPIObject['paths'] = {};
  const disabled = new Set(DISABLED_AUTH_PATHS.map((d) => d.replace(/:(\w+)/g, '{$1}')));
  for (const [p, item] of Object.entries(spec.paths)) {
    if (disabled.has(p)) continue;
    const ops: Record<string, Json> = {};
    for (const [method, op] of Object.entries(item)) {
      const operationId = (op.operationId as string | undefined) ?? `${method}_${p}`;
      ops[method] = { ...(JSON.parse(rename(JSON.stringify(op))) as Json), tags: ['auth'], operationId: `auth_${operationId}` };
    }
    paths[`${basePath}${p}`] = ops as never;
  }
  const schemas: Record<string, Json> = {};
  for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
    schemas[`Auth${name}`] = JSON.parse(rename(JSON.stringify(schema))) as Json;
  }
  return { paths, schemas };
}

export async function buildFullDocument(app: INestApplication, auth: Auth): Promise<OpenAPIObject> {
  const authSpec = await betterAuthPaths(auth);
  const doc = buildOpenApiDocument(app, STARTER_VERSION, {
    paths: authSpec.paths,
    tags: [{ name: 'auth', description: 'Better Auth (email OTP, sesión, cierre de sesión). Montado en /api/auth.' }],
  });
  doc.components!.schemas = { ...(doc.components!.schemas ?? {}), ...authSpec.schemas } as never;
  return doc;
}

/** Serves Swagger UI and the JSON document according to OPENAPI_DOCS (public|protected|disabled). */
export async function setupOpenApiDocs(app: INestApplication, deps: { auth: Auth; env: Env; db: DbHandle; features: FeatureFlags }): Promise<void> {
  if (deps.env.OPENAPI_DOCS === 'disabled') return;
  const document = await buildFullDocument(app, deps.auth);
  if (deps.env.OPENAPI_DOCS === 'protected') {
    app.use(['/api/docs', '/api/docs-json'], async (req: Request, res: Response, next: NextFunction) => {
      try {
        const session = await deps.auth.api.getSession({ headers: fromNodeHeaders(req.headers) });
        if (!session) return res.status(401).json({ error: { code: 'UNAUTHENTICATED', message: 'Sesión requerida' } });
        const actor = await loadActor({ db: deps.db.db, features: deps.features }, { userId: session.user.id, channel: 'panel' });
        if (!actor.permissions.has('api.docs')) return res.status(403).json({ error: { code: 'FORBIDDEN', message: 'Permiso requerido: api.docs' } });
        next();
      } catch {
        res.status(403).json({ error: { code: 'FORBIDDEN', message: 'Acceso denegado' } });
      }
    });
  }
  SwaggerModule.setup('api/docs', app, document, {
    jsonDocumentUrl: 'api/docs-json',
    customSiteTitle: 'Starter Kit API',
    swaggerOptions: { persistAuthorization: false, withCredentials: true },
  });
}
