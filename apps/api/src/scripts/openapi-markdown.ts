interface Op {
  operationId?: string;
  summary?: string;
  description?: string;
  tags?: string[];
  parameters?: { name: string; in: string; required?: boolean; schema?: { type?: string; enum?: unknown[]; format?: string }; description?: string }[];
  requestBody?: { content?: Record<string, { schema?: { $ref?: string; type?: string } }> };
  responses?: Record<string, { description?: string; content?: Record<string, { schema?: { $ref?: string; type?: string } }> }>;
}
interface Doc {
  info: { title: string; version: string; description?: string };
  paths: Record<string, Record<string, Op>>;
  components?: { schemas?: Record<string, unknown> };
}

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

function schemaName(s?: { $ref?: string; type?: string }): string {
  if (!s) return '—';
  if (s.$ref) return `\`${s.$ref.split('/').pop()}\``;
  return s.type ? `\`${s.type}\`` : 'objeto';
}

/** Deterministic Markdown reference generated from the OpenAPI document. */
export function renderMarkdown(doc: Doc): string {
  const byTag = new Map<string, { path: string; method: string; op: Op }[]>();
  for (const [path, item] of Object.entries(doc.paths)) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      const tag = op.tags?.[0] ?? 'otros';
      if (!byTag.has(tag)) byTag.set(tag, []);
      byTag.get(tag)!.push({ path, method, op });
    }
  }
  const lines: string[] = [
    '<!-- Generated by `pnpm api:docs:generate` from the NestJS application. Do not edit by hand. -->',
    `# Referencia API — ${doc.info.title} ${doc.info.version}`,
    '',
    doc.info.description ?? '',
    '',
    'Swagger UI: `/api/docs` (según `OPENAPI_DOCS`). Documento JSON: `/api/docs-json`. Artefacto versionado: `packages/api-client/openapi.json`.',
    '',
    '## Índice',
    '',
  ];
  const tags = [...byTag.keys()].sort();
  for (const t of tags) lines.push(`- [${t}](#${t.replace(/[^a-z0-9-]/gi, '-').toLowerCase()}) (${byTag.get(t)!.length})`);
  for (const t of tags) {
    lines.push('', `## ${t}`, '');
    for (const { path, method, op } of byTag.get(t)!.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))) {
      lines.push(`### \`${method.toUpperCase()} ${path}\``, '');
      lines.push(`- **operationId:** \`${op.operationId ?? '—'}\``);
      if (op.summary) lines.push(`- **Resumen:** ${op.summary}`);
      const params = op.parameters ?? [];
      if (params.length) {
        lines.push('- **Parámetros:**');
        for (const p of params) {
          const type = p.schema?.enum ? p.schema.enum.map((v) => `\`${String(v)}\``).join(' \\| ') : `\`${p.schema?.format ?? p.schema?.type ?? 'string'}\``;
          lines.push(`  - \`${p.name}\` (${p.in}${p.required ? ', requerido' : ''}): ${type}`);
        }
      }
      const body = op.requestBody?.content;
      if (body) {
        for (const [ct, c] of Object.entries(body)) lines.push(`- **Cuerpo** (\`${ct}\`): ${schemaName(c.schema)}`);
      }
      const responses = Object.entries(op.responses ?? {}).filter(([code]) => Number(code) < 400);
      for (const [code, r] of responses) {
        const content = Object.entries(r.content ?? {});
        lines.push(`- **${code}**: ${r.description ?? ''}${content.length ? ` — ${content.map(([ct, c]) => `\`${ct}\` ${schemaName(c.schema)}`).join(', ')}` : ''}`);
      }
      const errors = Object.keys(op.responses ?? {}).filter((c) => Number(c) >= 400);
      if (errors.length) lines.push(`- **Errores:** ${errors.join(', ')} (\`ErrorResponse\`)`);
      if (op.description) lines.push('', op.description.trim());
      lines.push('');
    }
  }
  lines.push('## Esquemas', '', `${Object.keys(doc.components?.schemas ?? {}).length} esquemas en \`components.schemas\` (ver \`openapi.json\`).`, '');
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
}
