/** Case- and accent-insensitive search over semantic names, Lucide names and Spanish keywords. */
export function searchIcons(term: string): IconName[] {
  const norm = (s: string) => s.normalize('NFD').replace(/\p{Diacritic}/gu, '').toLowerCase();
  const q = norm(term.trim());
  const all = Object.keys(ICONS) as IconName[];
  if (!q) return all;
  return all.filter((n) => norm(n).includes(q) || norm(ICON_LUCIDE[n]).includes(q) || norm(ICON_KEYWORDS[n]).includes(q));
}
